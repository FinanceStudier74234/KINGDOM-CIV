export function getBuildingDef(id: string): BuildingDef | undefined {
  return BUILDINGS.find(b => b.id === id);
}

export function getBuildingCost(def: BuildingDef, currentLevel: number, currentCount: number): number {
  const levelMult = Math.pow(def.costMultiplier, currentLevel);
  const countMult = Math.pow(1.3, currentCount);
  return Math.floor(def.baseCost * levelMult * countMult);
}

export function getBuildingUpgradeCost(def: BuildingDef, currentLevel: number): number {
  return Math.floor(def.baseCost * Math.pow(def.costMultiplier, currentLevel + 1) * 1.5);
}

export function getLevelName(def: BuildingDef, level: number): string {
  const names: Record<string, string[]> = {
    farm: ['Farm', 'Irrigated Farm', 'Plantation', 'Royal Farm', 'Grand Plantation'],
    wall: ['Wooden Wall', 'Stone Wall', 'Fortified Wall', 'Great Wall'],
    barracks: ['Training Ground', 'Barracks', 'War Academy', 'Fortress'],
  };
  return names[def.id]?.[level] || `${def.name} ${['I', 'II', 'III', 'IV', 'V'][level] || level + 1}`;
}
